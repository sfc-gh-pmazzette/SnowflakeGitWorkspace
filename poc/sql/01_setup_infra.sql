-- =============================================================================
-- Agent DevOps POC - 01: infrastructure (databases, schemas, roles, grants)
-- Run as: ACCOUNTADMIN       Re-runnable: yes
-- =============================================================================
USE ROLE ACCOUNTADMIN;

-- ---------- Databases / schemas ---------------------------------------------
CREATE DATABASE IF NOT EXISTS AGENT_POC_DEV COMMENT = 'Agent POC - DEV environment';
CREATE DATABASE IF NOT EXISTS AGENT_POC_QA  COMMENT = 'Agent POC - QA environment';
CREATE DATABASE IF NOT EXISTS AGENT_POC_OPS COMMENT = 'Agent POC - release machinery (Git repo, stage, procedures, log)';

CREATE SCHEMA IF NOT EXISTS AGENT_POC_DEV.SALES;
CREATE SCHEMA IF NOT EXISTS AGENT_POC_QA.SALES;
CREATE SCHEMA IF NOT EXISTS AGENT_POC_OPS.RELEASE;

-- ---------- Roles -------------------------------------------------------------
-- DEV_ROLE     : developers - build and iterate on the DEV agent
-- QA_ROLE      : testers    - can only RUN the QA agent (never edit it)
-- RELEASE_ROLE : CI / release owner - the only role that creates versions in QA
CREATE ROLE IF NOT EXISTS AGENT_POC_DEV_ROLE;
CREATE ROLE IF NOT EXISTS AGENT_POC_QA_ROLE;
CREATE ROLE IF NOT EXISTS AGENT_POC_RELEASE_ROLE;

GRANT ROLE AGENT_POC_DEV_ROLE     TO ROLE SYSADMIN;
GRANT ROLE AGENT_POC_QA_ROLE      TO ROLE SYSADMIN;
GRANT ROLE AGENT_POC_RELEASE_ROLE TO ROLE SYSADMIN;

SET MY_USER = CURRENT_USER();
GRANT ROLE AGENT_POC_DEV_ROLE     TO USER IDENTIFIER($MY_USER);
GRANT ROLE AGENT_POC_QA_ROLE      TO USER IDENTIFIER($MY_USER);
GRANT ROLE AGENT_POC_RELEASE_ROLE TO USER IDENTIFIER($MY_USER);

-- ---------- Common: warehouse + sample data -----------------------------------
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH TO ROLE AGENT_POC_DEV_ROLE;
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH TO ROLE AGENT_POC_QA_ROLE;
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH TO ROLE AGENT_POC_RELEASE_ROLE;

GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE AGENT_POC_DEV_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE AGENT_POC_QA_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE AGENT_POC_RELEASE_ROLE;

-- Cortex usage (agents / Cortex Analyst)
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AGENT_POC_DEV_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AGENT_POC_QA_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AGENT_POC_RELEASE_ROLE;

-- ---------- DEV: developers own the environment --------------------------------
GRANT USAGE ON DATABASE AGENT_POC_DEV TO ROLE AGENT_POC_DEV_ROLE;
GRANT USAGE ON SCHEMA AGENT_POC_DEV.SALES TO ROLE AGENT_POC_DEV_ROLE;
GRANT CREATE AGENT, CREATE SEMANTIC VIEW ON SCHEMA AGENT_POC_DEV.SALES TO ROLE AGENT_POC_DEV_ROLE;

-- ---------- QA: release role creates, testers only use ---------------------------
GRANT USAGE ON DATABASE AGENT_POC_QA TO ROLE AGENT_POC_RELEASE_ROLE;
GRANT USAGE ON SCHEMA AGENT_POC_QA.SALES TO ROLE AGENT_POC_RELEASE_ROLE;
GRANT CREATE AGENT ON SCHEMA AGENT_POC_QA.SALES TO ROLE AGENT_POC_RELEASE_ROLE;

GRANT USAGE ON DATABASE AGENT_POC_QA TO ROLE AGENT_POC_QA_ROLE;
GRANT USAGE ON SCHEMA AGENT_POC_QA.SALES TO ROLE AGENT_POC_QA_ROLE;
-- USAGE on the QA agent itself is granted by RELEASE_AGENT after the first release.

-- ---------- OPS: release machinery is owned/used by the release role ------------
GRANT USAGE ON DATABASE AGENT_POC_OPS TO ROLE AGENT_POC_RELEASE_ROLE;
GRANT USAGE ON SCHEMA AGENT_POC_OPS.RELEASE TO ROLE AGENT_POC_RELEASE_ROLE;

-- The release role grants USAGE on the QA agent it creates to the tester role.
-- (It owns the agent, so it can grant on it; nothing extra needed.)

SHOW ROLES LIKE 'AGENT_POC%';
